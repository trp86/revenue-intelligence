// The Detail page blocks (story #150). Measured fact (blue), Estimate (teal) and AI suggestion
// (purple) are separate cards, each with a heading, an icon and its token colour, so they are
// told apart by text and shape as well as colour.
import { CheckCircle2, Scale, Sparkles, type LucideIcon } from "lucide-react";
import type { ReactNode } from "react";

import type { OpportunityDetail } from "../../api/types";
import { cn } from "../../lib/utils";
import { factLabel } from "../../facts";
import { Metric } from "../Metric";
import { Badge } from "../ui/badge";

const TONES = {
  measured: { border: "border-measured", bg: "bg-measured-bg", text: "text-measured" },
  estimate: { border: "border-estimate", bg: "bg-estimate-bg", text: "text-estimate" },
  ai: { border: "border-ai", bg: "bg-ai-bg", text: "text-ai" },
} as const;

export function Panel({
  id,
  tone,
  icon: Icon,
  title,
  kicker,
  children,
  className,
}: {
  id: string;
  tone: keyof typeof TONES;
  icon: LucideIcon;
  title: string;
  kicker?: string;
  children: ReactNode;
  className?: string;
}) {
  const t = TONES[tone];
  return (
    <section aria-labelledby={id}
      className={cn("rounded-lg border border-border border-t-4 bg-surface shadow-sm", t.border, className)}>
      <header className={cn("flex items-center gap-2 rounded-t-md px-4 py-3 md:px-5", t.bg)}>
        <Icon className={cn("h-5 w-5", t.text)} aria-hidden="true" />
        <h2 id={id} className={cn("font-heading text-base font-semibold", t.text)}>{title}</h2>
        {kicker && <span className="ml-auto text-xs font-medium text-muted">{kicker}</span>}
      </header>
      <div className="p-4 md:p-5">{children}</div>
    </section>
  );
}

export function EvidencePanel({ facts }: { facts: OpportunityDetail["measured"] }) {
  return (
    <Panel id="measured-title" tone="measured" icon={CheckCircle2} title="Measured fact"
      kicker="Calculated from the sales data">
      {facts.length === 0 ? (
        <p className="text-sm text-muted">No measured facts were recorded for this opportunity.</p>
      ) : (
        <dl className="grid grid-cols-1 gap-3 sm:grid-cols-2">
          {facts.map((f) => (
            <div key={f.fact} className="rounded-md border border-border bg-surface-muted p-3">
              <dt className="text-xs font-medium text-muted">{factLabel(f.fact)}</dt>
              <dd className="mt-1 font-heading text-lg font-semibold text-text">
                <Metric metric={{ value: f.value, unit: f.unit, definition_id: f.definition_id }}
                  label={factLabel(f.fact)} />
              </dd>
            </div>
          ))}
        </dl>
      )}
    </Panel>
  );
}

export function EstimatePanel({ estimate }: { estimate: OpportunityDetail["estimate"] }) {
  return (
    <Panel id="estimate-title" tone="estimate" icon={Scale} title="Estimate" kicker="Not a measured result">
      <p className="text-xs font-medium text-muted">Value range, net sales</p>
      <p className="mt-1 flex flex-wrap items-baseline gap-1 font-heading text-2xl font-bold text-text">
        <Metric metric={estimate.value_low} label="value low" hideUnit />
        <span className="text-muted">to</span>
        <Metric metric={estimate.value_high} label="value high" hideUnit />
      </p>
      <p className="mt-3 flex items-center gap-2 text-sm">
        <span className="text-muted">Level</span>
        <Badge tone="opportunity">{estimate.value_level}</Badge>
      </p>
      {estimate.method && <p className="mt-3 text-xs text-muted">{estimate.method}</p>}
    </Panel>
  );
}

export function AiPanel({ children }: { children: ReactNode }) {
  return (
    <Panel id="ai-title" tone="ai" icon={Sparkles} title="AI suggestion" kicker="Generated by Gemini">
      {children}
    </Panel>
  );
}
