-- Silver sales: one row per bronze row, typed, with the original text kept (spec 01 S1, S2,
-- S10, S11). The bronze file path arrives as the parameter $bronze_file.
--
-- Column names are the bronze names (decision on issue #31): mixed case, and a few hold
-- characters such as ( ) % /, for example "Discount(%)_1". They are quoted everywhere, so the
-- rules against quoted and special-character identifiers are switched off for this file only.
-- noqa: disable=RF05,RF06
--
-- S1  Typed columns: dates (ISO text or Excel serial number), decimal(18, 4) amounts and
--     prices, and whole numbers. Each typed column is followed by <column>_raw, the original
--     bronze text, and by f_bad_<column>. Amounts with more than four decimals are rounded
--     to four (the original stays in _raw). Columns not listed as typed stay text and are
--     passed through untouched: codes, names and labels, including those that look numeric.
-- S2  Unparseable values become NULL and set f_bad_<column>; the row is kept. A blank cell
--     is NULL without a flag.
-- S10 Every bronze row is kept; this file filters nothing and sets no exclusion.
-- S11 All six candidate amount columns (Selling_Amount, NET_AMOUNT_1, AMOUNT_AF_DIS,
--     Net_Amount_2, Net_AMOUNT_3, TAX_AMOUNT) are typed and kept. Which one is net sales is
--     decided in the gold layer (spec 02), not here.
--
-- _source_row is the 1-based Excel row number (decision D5). It is a whole number here; the
-- build fails if it is not, because bronze always writes one.
create or replace table silver_sales as
with src as (
    select * from read_parquet($bronze_file)
)

